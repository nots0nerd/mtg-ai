#!/usr/bin/env node

/**
 * Fetch MTG Sets from Scryfall API
 * 
 * This script fetches all MTG sets from Scryfall and generates multiple output formats:
 * 1. mtg-sets.json - Full data for reference
 * 2. mtg-sets-compact.txt - Compact format for AI prompt
 * 3. valid-set-codes.js - Array of valid codes for validation
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const SCRYFALL_SETS_API = 'https://api.scryfall.com/sets';
const OUTPUT_DIR = path.join(__dirname, '..');

// Fetch data from URL
function fetchJSON(url) {
  return new Promise((resolve, reject) => {
    const options = {
      headers: {
        'User-Agent': 'MTG-AI-Search/1.0',
        'Accept': 'application/json'
      }
    };
    
    https.get(url, options, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        try {
          resolve(JSON.parse(data));
        } catch (error) {
          reject(error);
        }
      });
    }).on('error', reject);
  });
}

async function fetchMTGSets() {
  console.log('📡 Fetching MTG sets from Scryfall...\n');
  
  try {
    const response = await fetchJSON(SCRYFALL_SETS_API);
    
    if (!response || !response.data) {
      console.error('❌ Invalid response from Scryfall:', response);
      throw new Error('Invalid response structure from Scryfall API');
    }
    
    const sets = response.data;
    console.log(`✅ Fetched ${sets.length} sets\n`);
    
    // Sort by release date (most recent first)
    const sortedSets = sets
      .filter(set => set.set_type !== 'memorabilia' && set.set_type !== 'token')
      .sort((a, b) => new Date(b.released_at) - new Date(a.released_at));
    
    // 1. Save full data
    const fullDataPath = path.join(OUTPUT_DIR, 'mtg-sets.json');
    fs.writeFileSync(fullDataPath, JSON.stringify(sortedSets, null, 2));
    console.log(`✅ Saved full data: mtg-sets.json`);
    
    // 2. Generate compact format for AI prompt (last 40 sets + iconic ones)
    const recentSets = sortedSets.slice(0, 40);
    
    // Add iconic/popular older sets
    const iconicSetCodes = ['dom', 'rna', 'grn', 'war', 'thb', 'iko', 'znr', 'm21', 'm20', 'm19'];
    const iconicSets = sortedSets.filter(s => 
      iconicSetCodes.includes(s.code) && !recentSets.find(r => r.code === s.code)
    );
    
    const setsForPrompt = [...recentSets, ...iconicSets];
    
    let compactText = `# MTG Set Codes (Last ${recentSets.length} sets + Popular ones)\n`;
    compactText += `# Format: code | name | release_date\n\n`;
    
    setsForPrompt.forEach(set => {
      compactText += `${set.code.padEnd(5)} | ${set.name.padEnd(40)} | ${set.released_at}\n`;
    });
    
    const compactPath = path.join(OUTPUT_DIR, 'mtg-sets-compact.txt');
    fs.writeFileSync(compactPath, compactText);
    console.log(`✅ Saved compact format: mtg-sets-compact.txt (${setsForPrompt.length} sets)`);
    
    // 3. Generate validation array
    const validCodes = sortedSets.map(s => s.code);
    const validationCode = `// Auto-generated by scripts/fetch-mtg-sets.js
// Last updated: ${new Date().toISOString()}

module.exports = {
  VALID_SET_CODES: ${JSON.stringify(validCodes, null, 2)},
  
  SET_NAME_TO_CODE: {
${sortedSets.slice(0, 50).map(s => `    "${s.name}": "${s.code}"`).join(',\n')}
  },
  
  // Most recent 40 sets for AI prompt
  RECENT_SETS: ${JSON.stringify(
    recentSets.map(s => ({ code: s.code, name: s.name, date: s.released_at })),
    null,
    2
  )}
};
`;
    
    const validationPath = path.join(OUTPUT_DIR, 'valid-set-codes.js');
    fs.writeFileSync(validationPath, validationCode);
    console.log(`✅ Saved validation codes: valid-set-codes.js`);
    
    // 4. Generate condensed string for SYSTEM_PROMPT
    console.log('\n📋 SET CODES FOR SYSTEM_PROMPT (copy this):');
    console.log('═'.repeat(80));
    
    const promptSets = sortedSets.slice(0, 35);
    const promptLines = [];
    
    // Group by 3 for compact display
    for (let i = 0; i < promptSets.length; i += 3) {
      const line = promptSets.slice(i, i + 3)
        .map(s => `${s.code}:${s.name}`)
        .join(' | ');
      promptLines.push(line);
    }
    
    console.log('RECENT SETS:');
    promptLines.forEach(line => console.log(`- ${line}`));
    console.log('═'.repeat(80));
    
    console.log('\n📊 Summary:');
    console.log(`  - Total sets: ${sets.length}`);
    console.log(`  - After filtering: ${sortedSets.length}`);
    console.log(`  - Most recent: ${sortedSets[0].name} (${sortedSets[0].code})`);
    console.log(`  - For AI prompt: ${setsForPrompt.length} sets`);
    
  } catch (error) {
    console.error('❌ Error fetching sets:', error.message);
    process.exit(1);
  }
}

// Run the script
if (require.main === module) {
  fetchMTGSets();
}

module.exports = { fetchMTGSets };

